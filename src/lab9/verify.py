"""Generate submission reports and verify the local Core/Advanced/Expert gates.

Run from src/: python -m lab9.verify
Reports are generated by the harness; failures are recorded, never edited away.
"""
from __future__ import annotations

import json
from pathlib import Path

import yaml

from lab8.console import utf8_stdio
from lab9 import ci_check, gate, traps, variants
from lab9.eval import load_spec, run_eval
from lab9.graders import GRADERS


def main() -> int:
    utf8_stdio()
    variants.register()
    out = Path("reports")
    out.mkdir(exist_ok=True)

    def write(name, value):
        (out / name).write_text(json.dumps(value, ensure_ascii=False, indent=2,
                                         allow_nan=False) + "\n", encoding="utf-8")

    def evaluate(shape, spec, name, seeds=None):
        print(f"evaluating {name} ...", flush=True)
        report = run_eval(shape, spec, seeds)
        if report["evaluator_failures"]:
            raise RuntimeError(report["evaluator_failures"])
        write(name, report)
        return report

    v1 = load_spec(Path("config/metric_spec.yaml"))
    v2 = load_spec(Path("config/metric_spec_v2.yaml"))
    base1 = evaluate("swarm", v1, "baseline_v1.json")
    pr1 = evaluate("swarm", v1, "eval_pr.json")
    fixed = evaluate("fixed", v1, "eval_fixed.json")
    broken = evaluate("seeded_regression", v1, "eval_seeded_regression.json")
    checks = []

    def verdict(name, report, base, spec, want, base_spec=None):
        blocked, lines = gate.check(report, base, spec, base_spec)
        actual = "block" if blocked else "merge"
        checks.append({"case": name, "want": want, "actual": actual,
                       "blocked": blocked, "lines": lines})
        print(f"{name}: {actual}; {', '.join(blocked)}", flush=True)

    verdict("swarm_v1", pr1, base1, v1, "merge", v1)
    verdict("fixed_v1", fixed, base1, v1, "merge", v1)
    verdict("seeded_regression_v1", broken, base1, v1, "block", v1)
    baseline_problems = ci_check.check(pr1, base1, v1)
    bad_values = {m["id"]: "max" in m.get("threshold", {}) for m in v1["metrics"]
                  if m["id"] in GRADERS and m["id"] != "pass_rate"}
    flagged = lambda row: any(row.get(k) is value for k, value in bad_values.items())
    failed = [r for r in broken["rows"] if r["pass_rate"] is False]
    detection = sum(flagged(r) for r in failed) / len(failed) if failed else 0.0
    false_alarms = sum(flagged(r) for r in fixed["rows"]) / len(fixed["rows"])

    base2 = evaluate("swarm", v2, "baseline_v2.json")
    alternate = evaluate("swarm", v2, "aa_alternate_v2.json", [66, 77, 88, 99, 110])
    aa_delta = {key: alternate["metrics"][key] - value for key, value in base2["metrics"].items()}
    v2_reports = {}
    for shape, want in (("fixed", "merge"), ("honest_refactor", "merge"),
                        ("seeded_regression", "block"), ("slice_regression", "block"),
                        ("flaky_regression", "block")):
        report = evaluate(shape, v2, f"eval_{shape}_v2.json")
        v2_reports[shape] = report
        verdict(f"{shape}_v2", report, base2, v2, want, v2)

    # Save trap fixtures via their own generator, then verify all explicit reasons.
    traps.main(["--pr", "reports/eval_slice_regression_v2.json", "--baseline", "reports/baseline_v2.json",
                "--spec", "config/metric_spec_v2.yaml"])
    for name, (report, altered_spec) in traps.build(v2_reports["slice_regression"], v2).items():
        verdict(f"trap:{name}", report, base2, altered_spec or v2, "block", v2)
    summary = {"checks": checks, "ci_check_problems": baseline_problems,
               "detection": detection, "false_alarm_rate": false_alarms, "aa_delta": aa_delta,
               "mutation_killed": sum(c["want"] == c["actual"] == "block" for c in checks
                                      if c["case"] in {"seeded_regression_v2", "slice_regression_v2", "flaky_regression_v2"}),
               "mutation_false_alarms": sum(c["actual"] == "block" for c in checks
                                            if c["case"] in {"fixed_v2", "honest_refactor_v2"})}
    write("verification.json", summary)
    for name, spec in (("baseline_spec_v1.yaml", v1), ("baseline_spec_v2.yaml", v2)):
        (out / name).write_text(yaml.safe_dump(spec, allow_unicode=True, sort_keys=False), encoding="utf-8")
    ok = (all(c["want"] == c["actual"] for c in checks) and not baseline_problems
          and detection >= 0.8 and false_alarms <= 0.1 and "pass_rate" in checks[2]["blocked"])
    print(f"detection={detection:.2%}; false alarms={false_alarms:.2%}; exit {0 if ok else 1}", flush=True)
    return 0 if ok else 1


if __name__ == "__main__":
    raise SystemExit(main())
